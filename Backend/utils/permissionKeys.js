const STAFF_PERMISSIONS = [
    "VIEW_EMPLOYEES", "CREATE_EMPLOYEES", "EDIT_EMPLOYEES", "DELETE_EMPLOYEES", "MANAGE_EMPLOYEES",
    "VIEW_DEPARTMENTS", "CREATE_DEPARTMENTS", "EDIT_DEPARTMENTS", "DELETE_DEPARTMENTS", "MANAGE_DEPARTMENTS",
    "VIEW_DESIGNATIONS", "CREATE_DESIGNATIONS", "EDIT_DESIGNATIONS", "DELETE_DESIGNATIONS", "MANAGE_DESIGNATIONS",
    "VIEW_SERVICES", "CREATE_SERVICES", "EDIT_SERVICES", "DELETE_SERVICES", "MANAGE_SERVICES",
    "VIEW_CLIENTS", "CREATE_CLIENTS", "EDIT_CLIENTS", "DELETE_CLIENTS", "MANAGE_CLIENTS",
    "VIEW_LEADS", "CREATE_LEADS", "EDIT_LEADS", "DELETE_LEADS", "MANAGE_LEADS",
    "VIEW_PROJECTS", "CREATE_PROJECTS", "EDIT_PROJECTS", "DELETE_PROJECTS", "MANAGE_PROJECTS",
    "VIEW_INTERVIEWS", "CREATE_INTERVIEWS", "EDIT_INTERVIEWS", "DELETE_INTERVIEWS", "MANAGE_INTERVIEWS",
    "APPROVE_LEAVE",
    "VIEW_SALARY", "MANAGE_SALARY",
    "MANAGE_PERMISSIONS", "MANAGE_SETTINGS",
];

const CLIENT_PERMISSIONS = [
    "CLIENT_VIEW_PROJECTS",
    "CLIENT_SUPPORT",
];

const CLIENT_DEFAULT_PERMISSIONS = [...CLIENT_PERMISSIONS];

const sanitizePermissions = (userType, permissions) => {
    const incoming = Array.isArray(permissions)
        ? [...new Set(permissions.map((key) => String(key || "").trim()).filter(Boolean))]
        : [];
    const allowed = userType === "CLIENT" ? CLIENT_PERMISSIONS : STAFF_PERMISSIONS;
    return incoming.filter((key) => allowed.includes(key));
};

module.exports = {
    STAFF_PERMISSIONS,
    CLIENT_PERMISSIONS,
    CLIENT_DEFAULT_PERMISSIONS,
    sanitizePermissions,
};
